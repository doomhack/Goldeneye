u8 *bloodDecodeFrame(u8 *src, u8 width, u8 height, u8 *dst, u8 *edgeOut)
{
    u8 value;
    u8 filled;
    u8 edge;
    u8 run;

    edge = *src++;
    *edgeOut = edge;

    do
    {
        s32 unused;
        run = *src++;
        unused = run;
        
        value = 0xFF;

        if (run == 0xFF)
        {
            filled = 0;
            for (run = *src++; run != 0xFF; value ^= 0xff, run = *src++ )
            {
                filled += run;

                while (run-- > 0)
                {
                    *dst++ = value;
                }
            }
            
            while (filled++ < width)
            {
                *dst++ = value;
            }
            
            height--;
        }
        else
        {
            filled = edge + (run & 0x1f);
            run = (run >> 5) + 1;
            height -= run;
            
            do
            {
                value = filled;
                while (value-- > 0)
                {
                    *dst++ = 0xff;
                }
                
                value = width - filled;
                while (value-- > 0)
                {
                    *dst++ = 0;
                }
            } while (--run > 0);
        }
    } while (height > 0);
    
    return src;
}


void bloodPack4Bit(u8* src, u16 count, u8* dst)
{
    while (count-- > 0)
    {
        *dst++ = (src[0] & 0xF0) | (src[1] >> 4);
        src += 2;
    }
}


// Averages 4 pixel data, ending on "second" row.
void bloodSmoothUpLeft(u8 *src, s32 height, u8 *dst)
{
    s32 i;
    s32 j;

    src += 0x61;
    dst += 0x61;

    for (i = 1; i < height - 1; i++, dst += 2, src += 2) {
        for (j = 1; j < 0x5f; j++, dst++, src++) {
            *dst = (src[-1] + src[0] + src[-0x61] + src[-0x60] + 2) >> 2;
        }
    }
}


// Averages 4 pixel data, ending on "first" row.
void bloodSmoothDownRight(u8 *src, s32 height, u8 *dst)
{
    s32 i;
    s32 j;

    src += 0x61;
    dst += 0x61;

    for (i = 1; i < height - 1; i++, dst += 2, src += 2) {
        for (j = 1; j < 0x5f; j++, dst++, src++) {
            *dst = (src[1] + src[0] + src[0x61] + src[0x60] + 2) >> 2;
        }
    }
}


/**
 * Converts the decoded blood frame from column-major to row-major order.
 */
void bloodImgTranspose(u8 *src, s32 srcwidth, s32 srcheight, u8 *dst)
{
    s32 pixelcount;
    u8 *rowend;
    u8 *nextRowEnd;
    u8 *out;
    u8 *in;
    u8 *end;

    pixelcount = srcwidth * srcheight;
    in = src;
    out = dst;
    end = src + pixelcount;
    nextRowEnd = src + srcwidth;

    do
    {
        rowend = nextRowEnd;

        do
        {
            *out = *in++;
            nextRowEnd += 1;
            out += srcheight;
            
        } while (in < rowend);

        out = (out - (pixelcount)) + 1;
        
    } while (in < end);
}


