#!/usr/bin/env python3
"""Renders the "Expansion Pak required" message to a 4-bit greyscale bitmap
and writes it as a C header (src/exppak_msg.h). Needs Pillow and DejaVu fonts;
the header is checked in, so the build does not."""
import sys
from PIL import Image, ImageDraw, ImageFont

FONTDIR = '/usr/share/fonts/truetype/dejavu/'
LINES = [
    ('EXPANSION PAK REQUIRED', 'DejaVuSans-Bold.ttf', 20),
    ('Switch off, insert the Expansion Pak and try again.', 'DejaVuSans.ttf', 11),
]
GAP = 14

def main(out):
    rendered = []
    for text, font, size in LINES:
        f = ImageFont.truetype(FONTDIR + font, size)
        l, t, r, b = f.getbbox(text)
        img = Image.new('L', (r - l, b - t), 0)
        ImageDraw.Draw(img).text((-l, -t), text, font=f, fill=255)
        rendered.append(img)
    w = max(i.width for i in rendered)
    w += w & 1
    h = sum(i.height for i in rendered) + GAP * (len(rendered) - 1)
    canvas = Image.new('L', (w, h), 0)
    y = 0
    for img in rendered:
        canvas.paste(img, ((w - img.width) // 2, y))
        y += img.height + GAP
    px = canvas.load()
    data = []
    for y in range(h):
        for x in range(0, w, 2):
            data.append(((px[x, y] >> 4) << 4) | (px[x + 1, y] >> 4))
    with open(out, 'w') as fp:
        fp.write('// Generated by tools/mkexppakmsg.py, do not edit.\n')
        fp.write('#define EXPPAK_MSG_WIDTH %d\n#define EXPPAK_MSG_HEIGHT %d\n\n' % (w, h))
        fp.write('// 4 bits per pixel, high nibble first\n')
        fp.write('static const u8 g_ExpPakMsgBitmap[%d] = {\n' % len(data))
        for i in range(0, len(data), 16):
            fp.write('    ' + ', '.join('0x%02X' % b for b in data[i:i + 16]) + ',\n')
        fp.write('};\n')
    print(w, h, len(data))

main(sys.argv[1] if len(sys.argv) > 1 else 'src/exppak_msg.h')
